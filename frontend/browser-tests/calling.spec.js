import { test, expect } from '@playwright/test'

test('dashboard to receiver: ringing, consent, microphone turn, confirmation and JSON', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByLabel('Administrator token').fill(process.env.AC_BROWSER_TEST_TOKEN)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your call desk', exact: true })).toBeVisible()
  await page.getByLabel('Recipient display name').fill('Browser test recipient')
  await page.getByRole('button', { name: 'Create private invitation' }).click()
  const invite = await page.getByLabel('Invitation · expires in 5 minutes').inputValue()
  const recipientContext = await browser.newContext({ permissions: ['microphone'] })
  const receiver = await recipientContext.newPage()
  try {
    await receiver.goto(invite)
    await receiver.getByRole('button', { name: 'Connect securely' }).click()
    await expect(receiver.getByText('Available · waiting for a call')).toBeVisible()
    await expect(page.getByRole('option', { name: 'Browser test recipient · Available' })).toBeEnabled()
    await page.getByLabel('Connected recipient').selectOption({ label: 'Browser test recipient · Available' })
    await page.getByRole('button', { name: 'Initiate internet call' }).click()
    await expect(receiver.getByRole('heading', { name: 'Incoming AI call' })).toBeVisible()
    await receiver.getByRole('button', { name: 'Accept', exact: true }).click()
    const play = receiver.getByRole('button', { name: 'Play reply', exact: true })
    await expect(receiver.getByRole('button', { name: 'I consent', exact: true })).toBeVisible()
    if (await play.isVisible()) await play.click()
    await expect(receiver.getByRole('button', { name: 'I consent', exact: true })).toBeEnabled()
    await receiver.getByRole('button', { name: 'I consent', exact: true }).click()
    const speak = receiver.getByRole('button', { name: 'Speak', exact: true })
    if (await play.isVisible()) await play.click()
    await expect(speak).toBeEnabled()
    await speak.click()
    await expect(receiver.getByRole('button', { name: 'Send turn', exact: true })).toBeVisible()
    await receiver.waitForTimeout(800)
    await receiver.getByRole('button', { name: 'Send turn', exact: true }).click()
    const confirm = receiver.getByRole('button', { name: 'Confirm details', exact: true })
    await expect(confirm).toBeVisible()
    if (await play.isVisible()) await play.click()
    await expect(confirm).toBeEnabled()
    await confirm.click()
    await expect(receiver.getByText('completed', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'View JSON', exact: true })).toBeVisible({ timeout: 10000 })
    await page.getByRole('button', { name: 'View JSON', exact: true }).click()
    await expect(page.locator('pre')).toContainText('Clinic opening hours')
    const cookies = await recipientContext.cookies()
    expect(cookies.some(c => c.name === 'ac_admin')).toBe(false)
    expect(cookies.find(c => c.name === 'ac_receiver').httpOnly).toBe(true)
  } finally {
    await recipientContext.close()
  }
})
